# DBTITLE 1,Processes View
def create_process_view(unitcatalog):
    spark.sql(f"USE CATALOG {unitcatalog}") 
    spark.sql(f"""
    CREATE OR REPLACE VIEW 0_par.vw_processos
        AS SELECT 
            trim(replace(replace(regexp_extract(args, "sep{{.*?}}",0),"sep{{", ""),"}}","")) as sep, 
            trim(replace(replace(regexp_extract(args, "encode{{.*?}}",0),"encode{{", ""),"}}","")) as encode, 
            trim(replace(replace(regexp_extract(args, "escape{{.*?}}",0),"escape{{", ""),"}}","")) as escape, 
            trim(replace(replace(regexp_extract(args, "quote{{.*?}}",0),"quote{{", ""),"}}","")) as quote, 
            trim(replace(replace(regexp_extract(args, "sheetIndex{{.*?}}",0),"sheetIndex{{", ""),"}}","")) as sheetIndex, 
            trim(replace(replace(regexp_extract(args, "ndias{{.*?}}",0),"ndias{{", ""),"}}","")) as ndias, 
            trim(replace(regraIncremental,"ndias{{}}",replace(replace(regexp_extract(args, "ndias{{.*?}}",0),"ndias{{", ""),"}}",""))) as regraIncrementalParametrizada, 
            case when queryOrigem <> '' then 1 else header end as headerParametrizado,
            * 
        FROM {unitCatalogNamePrd}.0_par.processos             
    """)
create_process_view(unitCatalogNamePrd)


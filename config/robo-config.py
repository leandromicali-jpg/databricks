def delete_files(path):
    try:
        for filepath in dbutils.fs.ls(path):
            file = str(filepath).split('\'')[1]
            dbutils.fs.rm(file,True)
    except:
        print('caminho nao encontrado: ' + path)
delete_files(f"{externalLocationPrd}/filestore/arquivosteste/csv")

df.write.option("header", True)\
        .option("delimiter", ",")\
        .option("quote", "\"")\
        .option("escape", "\\")\
        .option("encoding", "ISO-8859-1")\
        .mode("overwrite")\
        .csv(f"{externalLocationPrd}/filestore/arquivosteste/csv")
